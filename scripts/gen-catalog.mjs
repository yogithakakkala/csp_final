#!/usr/bin/env node
/**
 * Generates two files from src/data/catalog.ts so the catalogue has one source:
 *   api/_knowledge.ts                 – compact scheme/service facts for SachiBot's system prompt
 *   supabase/catalog_seed.sql         – upserts every scheme & service into public.schemes
 * Runs automatically before `npm run build`. Re-run after editing the catalogue:
 *   node scripts/gen-catalog.mjs
 */
import { build } from 'esbuild';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = mkdtempSync(join(tmpdir(), 'catalog-'));
const out = join(dir, 'catalog.mjs');

await build({
  entryPoints: [join(root, 'src/data/catalog.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: out,
  alias: { '@': join(root, 'src') },
  // catalog.ts only imports types from profile.ts, but keep supabase out just in case
  external: ['@supabase/supabase-js'],
  logLevel: 'silent',
});
const { CATALOG, STATUS_LABEL } = await import(pathToFileURL(out).href);
rmSync(dir, { recursive: true, force: true });

const live = CATALOG.filter((c) => c.status !== 'retired').sort((a, b) => a.priority - b.priority);

/* ── SachiBot knowledge ─────────────────────────────────────────────── */
const line = (c) => {
  const path = `/${c.kind === 'service' ? 'services' : 'schemes'}/${c.id}`;
  const bits = [
    `[${c.name.en} / ${c.name.te}](${path})`,
    c.status !== 'active' ? STATUS_LABEL[c.status].en : '',
    c.benefit ? `benefit: ${c.benefit.en}` : '',
    c.fee ? `fee: ${c.fee.en}` : '',
    c.time ? `time: ${c.time.en}` : '',
    c.who.length ? `who: ${c.who.map((w) => w.en).join('; ')}` : '',
    `docs: ${c.docs.map((d) => d.en).join('; ')}`,
    `where: ${c.where.en}`,
  ].filter(Boolean);
  return `- ${bits.join(' | ')}`;
};
const knowledge = [
  'SCHEMES:',
  ...live.filter((c) => c.kind === 'scheme').map(line),
  '',
  'SACHIVALAYAM SERVICES (certificates etc.):',
  ...live.filter((c) => c.kind === 'service').map(line),
].join('\n');

writeFileSync(
  join(root, 'api/_knowledge.ts'),
  `// Generated by scripts/gen-catalog.mjs from src/data/catalog.ts — do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(knowledge)};\n`,
);

/* ── Database seed ──────────────────────────────────────────────────── */
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (xs) => (xs.length ? `array[${xs.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const rows = live.map(
  (c) => `  (${q(c.id)}, ${q(c.name.en)}, ${q(c.name.te)}, ${q(c.summary.en)}, ${arr(c.docs.map((d) => d.en))})`,
);
const sql = `-- Generated by scripts/gen-catalog.mjs from src/data/catalog.ts — do not edit by hand.
-- Adds / refreshes every scheme and Sachivalayam service. Safe to re-run.
-- Document lists are reset to the catalogue's (the app shows them in Telugu and English;
-- a list a staff member edits later is shown as they typed it).
insert into public.schemes (id, name, name_telugu, description, required_documents) values
${rows.join(',\n')}
on conflict (id) do update set
  name = excluded.name,
  name_telugu = excluded.name_telugu,
  description = excluded.description,
  required_documents = excluded.required_documents;
`;
writeFileSync(join(root, 'supabase/catalog_seed.sql'), sql);

console.log(`catalogue: ${live.filter((c) => c.kind === 'scheme').length} schemes, ${live.filter((c) => c.kind === 'service').length} services → api/_knowledge.ts, supabase/catalog_seed.sql`);
